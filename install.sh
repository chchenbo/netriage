#!/usr/bin/env bash
# Install netriage so that the command `netriage` works from any directory.
#
#   sudo bash install.sh      system-wide: /usr/local/bin/netriage (recommended)
#   bash install.sh           this user only: <python user scripts dir>
#
# System-wide is the mode you want: it is on every PATH, it works for `sudo
# netriage` too, and the access point scan needs root anyway.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC="$HERE/netriage"

if [ ! -d "$SRC" ]; then
    echo "error: package not found at $SRC" >&2
    echo "       run this from the directory that contains netriage/" >&2
    exit 1
fi

if ! command -v python3 >/dev/null 2>&1; then
    echo "error: python3 not found" >&2
    exit 1
fi

on_path() {
    case ":$PATH:" in
        *":$1:"*) return 0 ;;
        *) return 1 ;;
    esac
}

if [ "$(id -u)" -eq 0 ]; then
    MODE="system"
    BIN_DIR="/usr/local/bin"
    TARGET_DIR="$(python3 - <<'ENDPY'
import sys
for path in sys.path:
    if path.startswith("/usr/local/") and path.endswith(("dist-packages", "site-packages")):
        print(path)
        break
ENDPY
)"
    if [ -z "$TARGET_DIR" ] || [ ! -d "$TARGET_DIR" ]; then
        TARGET_DIR="/usr/local/lib/python$(python3 -c 'import sys; print("%d.%d" % sys.version_info[:2])')/dist-packages"
    fi
else
    MODE="user"
    TARGET_DIR="$(python3 -c 'import site; print(site.getusersitepackages())')"
    # the directory Python itself uses for user-facing scripts:
    # ~/.local/bin on Linux
    BIN_DIR="$(python3 - <<'ENDPY'
import sysconfig
try:
    print(sysconfig.get_path("scripts", scheme="posix_user"))
except Exception:
    import site
    print(site.USER_BASE + "/bin")
ENDPY
)"
fi

if [ -z "${TARGET_DIR:-}" ] || [ -z "${BIN_DIR:-}" ]; then
    echo "error: could not determine the install directories" >&2
    exit 1
fi

LEGACY="$HOME/.local/share/netriage"
if [ -d "$LEGACY" ] && [ -f "$LEGACY/netriage/cli.py" ]; then
    echo "removing previous install at $LEGACY"
    rm -rf "$LEGACY"
fi

# The interpreter used now may not be the python3 on PATH later (pyenv, conda,
# a different /usr/local/bin/python3). Bake in the absolute path.
PYTHON="$(python3 -c 'import sys; print(sys.executable)')"
if [ -z "$PYTHON" ] || [ ! -x "$PYTHON" ]; then
    echo "error: could not determine the python interpreter path" >&2
    exit 1
fi

mkdir -p "$TARGET_DIR" "$BIN_DIR"
rm -rf "$TARGET_DIR/netriage"
cp -a "$SRC" "$TARGET_DIR/netriage"
find "$TARGET_DIR/netriage" -name __pycache__ -type d -prune -exec rm -rf {} + 2>/dev/null || true
find "$TARGET_DIR/netriage" -name '*.pyc' -delete 2>/dev/null || true

# The command is a Python script, not a shell wrapper: the kernel starts it
# with the interpreter from the shebang, and sys.path[0] becomes the script's
# own directory rather than the current one. Run it from inside a checkout of
# this repository and you still get the installed copy.
case "$TARGET_DIR" in
    *'"'*|*'\'*)
        cat > "$BIN_DIR/netriage" <<LAUNCHER
#!/bin/sh
# Generated by the netriage installer - safe to delete.
exec "$PYTHON" -m netriage "\$@"
LAUNCHER
        ;;
    *)
        cat > "$BIN_DIR/netriage" <<LAUNCHER
#!$PYTHON
# Generated by the netriage installer - safe to delete.
import sys

sys.path.insert(0, "$TARGET_DIR")

from netriage.cli import main  # noqa: E402

sys.exit(main())
LAUNCHER
        ;;
esac
chmod 0755 "$BIN_DIR/netriage"

echo "mode         $MODE"
echo "package      $TARGET_DIR/netriage"
echo "interpreter  $PYTHON"
echo "command      $BIN_DIR/netriage"

# ---------------------------------------------------------------- PATH
# One place that knows where a shell startup line goes, so the same repair is
# not written twice and cannot drift.
add_to_shell_startup() {
    dir="$1"
    shell_name="$(basename "${SHELL:-/bin/sh}")"
    case "$shell_name" in
        zsh)  candidates="$HOME/.zprofile $HOME/.zshrc" ;;
        bash) candidates="$HOME/.profile $HOME/.bashrc" ;;
        *)    candidates="$HOME/.profile" ;;
    esac

    touched=""
    for rc in $candidates; do
        [ -f "$rc" ] || continue
        grep -q 'added by the netriage installer' "$rc" && continue
        {
            echo ''
            echo '# added by the netriage installer'
            echo "case \":\$PATH:\" in"
            echo "    *\":$dir:\"*) ;;"
            echo "    *) PATH=\"$dir:\$PATH\" ;;"
            echo 'esac'
            echo 'export PATH'
        } >> "$rc"
        touched="$touched $(basename "$rc")"
    done

    if [ -z "$touched" ]; then
        # a minimal machine may have none of them; create the right one
        case "$shell_name" in
            zsh) rc="$HOME/.zprofile" ;;
            *)   rc="$HOME/.profile" ;;
        esac
        {
            echo '# added by the netriage installer'
            echo "case \":\$PATH:\" in"
            echo "    *\":$dir:\"*) ;;"
            echo "    *) PATH=\"$dir:\$PATH\" ;;"
            echo 'esac'
            echo 'export PATH'
        } >> "$rc"
        touched=" $(basename "$rc") (created)"
    fi
    echo "$touched"
}

fresh_shell_finds_it() {
    env -i HOME="$HOME" USER="${USER:-$(id -un)}" TERM=dumb \
        sh -lc 'command -v netriage >/dev/null 2>&1'
}

if on_path "$BIN_DIR"; then
    echo "path         ok ($BIN_DIR is on PATH)"
else
    LINKED=""
    for candidate in "$HOME/bin" /usr/local/bin; do
        [ "$candidate" = "$BIN_DIR" ] && continue
        if [ -d "$candidate" ] && [ -w "$candidate" ] && on_path "$candidate"; then
            ln -sf "$BIN_DIR/netriage" "$candidate/netriage"
            LINKED="$candidate"
            break
        fi
    done

    if [ -n "$LINKED" ]; then
        echo "path         linked into $LINKED (already on PATH)"
        BIN_DIR="$LINKED"
    else
        touched="$(add_to_shell_startup "$BIN_DIR")"
        echo "path         $BIN_DIR added to:$touched"
        echo "             for this shell now:  export PATH=\"$BIN_DIR:\$PATH\""
    fi
fi

# ---------------------------------------------------------------- tools
echo
echo "checking optional tools"
echo "  (netriage reads these; a missing one shows as 'unknown', never as zero)"
missing=""
for tool in iw ethtool lldpcli dig curl ping nmcli; do
    if command -v "$tool" >/dev/null 2>&1; then
        printf "  %-9s ok\n" "$tool"
    else
        printf "  %-9s MISSING\n" "$tool"
        missing="$missing $tool"
    fi
done
if [ -n "$missing" ]; then
    echo
    echo "install them with:"
    echo "  sudo apt install -y iw ethtool lldpd dnsutils curl iputils-ping network-manager"
fi

# ---------------------------------------------------------------- verify
echo
echo "checking the command itself"

if ( cd / && env -u PYTHONPATH "$BIN_DIR/netriage" --version >/dev/null 2>&1 ); then
    echo "  $BIN_DIR/netriage  ok"
else
    echo "error: $BIN_DIR/netriage does not run" >&2
    exit 1
fi

if command -v netriage >/dev/null 2>&1; then
    echo "  this shell                     ok"
else
    echo "  this shell                     not yet"
    echo "      your shell may have cached the old answer. Open a new terminal,"
    echo "      or run:  rehash"
fi

# A brand new login shell is what the user will actually get next time.
if fresh_shell_finds_it; then
    echo "  a new terminal                 ok"
else
    echo "  a new terminal                 would not find it - fixing"
    touched="$(add_to_shell_startup "$BIN_DIR")"
    echo "      wrote:$touched"
    if fresh_shell_finds_it; then
        echo "  a new terminal                 ok now"
    else
        echo "  still not found. Add this line to your shell startup file" >&2
        echo "  by hand, then open a new terminal:" >&2
        echo "      export PATH=\"$BIN_DIR:\$PATH\"" >&2
        echo "  see TROUBLESHOOTING.md" >&2
    fi
fi

echo
echo "if anything still says 'command not found', see TROUBLESHOOTING.md"
